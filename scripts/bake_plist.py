#!/usr/bin/env python3
"""Turns config/GNUnlock.plist into a C header so the plist is baked into the
dylib. That keeps the "no file to smuggle into the bundle" property: edit the
plist, rebuild, get a new dylib. Runtime overrides still work (bundle plist or
Documents/GNUnlock.plist).

usage: bake_plist.py <in.plist> <out.h>
"""

import os
import plistlib
import sys


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2

    source, destination = sys.argv[1], sys.argv[2]

    with open(source, "rb") as handle:
        raw = handle.read()

    # Validate before baking: a broken plist at runtime is a silent no-op.
    plist = plistlib.loads(raw)
    if not isinstance(plist, dict):
        print("error: top level object must be a dict", file=sys.stderr)
        return 1

    lines = [
        "// generated by scripts/bake_plist.py - do not edit",
        "#pragma once",
        "",
        "static const unsigned char GNBakedConfigData[] = {",
    ]
    for offset in range(0, len(raw), 16):
        chunk = raw[offset:offset + 16]
        lines.append("    " + ", ".join("0x%02x" % byte for byte in chunk) + ",")
    lines.append("};")
    lines.append("static const unsigned int GNBakedConfigSize = %d;" % len(raw))
    lines.append("")

    os.makedirs(os.path.dirname(os.path.abspath(destination)), exist_ok=True)
    with open(destination, "w") as handle:
        handle.write("\n".join(lines))

    print("baked %s (%d bytes, %d top level keys)"
          % (destination, len(raw), len(plist)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
