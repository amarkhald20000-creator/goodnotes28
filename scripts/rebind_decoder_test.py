#!/usr/bin/env python3
"""rebind_decoder_test.py - prove the chained-fixups import decoder, not by eye.

    python3 scripts/rebind_decoder_test.py

The crash this exists for
-------------------------
v9 died with SIGBUS inside strcmp, called from GNRebindSymbolInAppImages while
dyld was initialising. The import table was being indexed with the wrong entry
size for the import format, so the "symbol name" offset came out of the addend
array instead of the imports, `symbols + offset` pointed outside the string
pool, and strcmp read a page it was not allowed to read.

None of that needs a device to test, and none of it is visible by reading the
source. So this script:

  1. extracts GNImportEntrySize() and GNImportSymbolName() *from src/GNRebind.m
     itself* (not a copy - a regression in the source has to fail here),
  2. builds synthetic fixups blobs in the three import formats,
  3. checks every name resolves to the entry it belongs to, that the wrong
     stride is actually caught, and that every out-of-range input returns NULL.

It runs with the host C compiler, in well under a second, and it is part of
scripts/build.sh - so a broken decoder fails the build instead of the phone.
"""

import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "GNRebind.m"


def extract_block(text, signature):
    """The full text of one C function, from its signature to its closing brace."""
    start = text.index(signature)
    depth = 0
    index = text.index("{", start)
    while index < len(text):
        character = text[index]
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                return text[start:index + 1]
        elif character == '"':
            index = text.index('"', index + 1)
        index += 1
    raise SystemExit("unbalanced braces after: %s" % signature)


def extract_struct(text, name):
    match = re.search(r"typedef struct \{[^}]*\} %s;" % re.escape(name), text, re.S)
    if not match:
        raise SystemExit("could not find the %s declaration in src/GNRebind.m" % name)
    return match.group(0)


def extract_defines(text, names):
    lines = []
    for name in names:
        match = re.search(r"^#define %s\s+(.+)$" % re.escape(name), text, re.M)
        if not match:
            raise SystemExit("could not find #define %s in src/GNRebind.m" % name)
        lines.append("#define %s %s" % (name, match.group(1).strip()))
    return "\n".join(lines)


def build_harness():
    text = SOURCE.read_text(encoding="utf-8")

    parts = [
        "/* generated by scripts/rebind_decoder_test.py - do not edit */",
        "#include <stdint.h>",
        "#include <stdio.h>",
        "#include <string.h>",
        "#include <stdlib.h>",
        "#define NULL ((void *)0)",
        extract_defines(text, [
            "GN_SYMBOLS_UNCOMPRESSED",
            "GN_IMPORT",
            "GN_IMPORT_ADDEND",
            "GN_IMPORT_ADDEND64",
        ]),
        extract_struct(text, "GNFixupsHeader"),
        extract_block(text, "static uint32_t GNImportEntrySize"),
        extract_block(text, "static const char *GNImportSymbolName"),
        HARNESS_MAIN,
    ]
    return "\n\n".join(parts)


HARNESS_MAIN = r"""
/* ------------------------------------------------------------------ tests */

static uint8_t gBlob[4096];
static const char *gNames = "abort\0_exit\0strcmp\0";
#define NAME_COUNT 3
static const uint32_t kNameOffsets[NAME_COUNT] = { 0, 6, 12 };

/* Apple's layout, written out independently of the code under test. If the
   fixture were laid out with GNImportEntrySize() itself, a wrong stride would
   produce a wrong blob too and the two errors would cancel out - which is
   exactly how the v9 defect survived every check that existed at the time. */
static size_t apple_entry_size(uint32_t format) {
    switch (format) {
        case GN_IMPORT:        return 4;
        case GN_IMPORT_ADDEND: return 4;
        case GN_IMPORT_ADDEND64: return 8;
        default: return 0;
    }
}

static size_t import_table_size(uint32_t format, uint32_t count) {
    return apple_entry_size(format) * count;
}

static size_t addend_array_size(uint32_t format, uint32_t count) {
    if (format == GN_IMPORT_ADDEND) return 4u * count;
    if (format == GN_IMPORT_ADDEND64) return 8u * count;
    return 0;
}

/* Builds a blob that is laid out the way dyld lays one out: header, import
   table, addend array (formats 2 and 3), then the NUL separated name pool. */
static GNFixupsHeader *build_blob(uint32_t format, uint32_t count, size_t *outSize) {
    memset(gBlob, 0, sizeof(gBlob));

    GNFixupsHeader *header = (GNFixupsHeader *)gBlob;
    header->fixups_version = 0;
    header->starts_offset = 0;
    header->imports_count = count;
    header->imports_format = format;
    header->symbols_format = GN_SYMBOLS_UNCOMPRESSED;

    size_t entrySize = apple_entry_size(format);
    size_t importsOffset = sizeof(GNFixupsHeader);
    size_t tableSize = import_table_size(format, count);
    size_t addendsOffset = importsOffset + tableSize;
    size_t addendsSize = addend_array_size(format, count);
    size_t symbolsOffset = addendsOffset + addendsSize;
    size_t namesSize = sizeof("abort\0_exit\0strcmp\0") - 1;

    header->imports_offset = (uint32_t)importsOffset;
    header->symbols_offset = (uint32_t)symbolsOffset;

    for (uint32_t i = 0; i < count; i++) {
        uint32_t nameOffset = kNameOffsets[i % NAME_COUNT];
        uint8_t *entry = gBlob + importsOffset + (size_t)i * entrySize;

        if (format == GN_IMPORT_ADDEND64) {
            uint64_t raw = (uint64_t)nameOffset << 32;
            memcpy(entry, &raw, sizeof(raw));
        } else {
            uint32_t raw = (nameOffset & 0x7FFFFFu) << 9;
            memcpy(entry, &raw, sizeof(raw));
        }

        /* A plausible addend so the array is not all zeroes: if the decoder
           ever reads an entry out of here instead of the table, the resulting
           "name" is this value, not a name offset. */
        if (format == GN_IMPORT_ADDEND) {
            uint32_t addend = 0xDEAD0000u + i;
            memcpy(gBlob + addendsOffset + (size_t)i * 4, &addend, sizeof(addend));
        } else if (format == GN_IMPORT_ADDEND64) {
            uint64_t addend = 0xDEADBEEF00000000ull + i;
            memcpy(gBlob + addendsOffset + (size_t)i * 8, &addend, sizeof(addend));
        }
    }

    memcpy(gBlob + symbolsOffset, gNames, namesSize);
    *outSize = symbolsOffset + namesSize;
    return header;
}

static int gFailures = 0;

static void check(int condition, const char *what, const char *detail) {
    if (condition) return;
    printf("  FAIL  %s%s%s\n", what, detail ? " - " : "", detail ? detail : "");
    gFailures++;
}

static const char *kExpected[NAME_COUNT] = { "abort", "_exit", "strcmp" };

static void test_format(uint32_t format, const char *label) {
    size_t size = 0;
    GNFixupsHeader *header = build_blob(format, NAME_COUNT, &size);

    for (uint32_t i = 0; i < NAME_COUNT; i++) {
        const char *name = GNImportSymbolName(header, gBlob, size, i);
        char what[128];
        snprintf(what, sizeof(what), "%s ordinal %u resolves to its own entry", label, i);
        check(name && strcmp(name, kExpected[i]) == 0, what, name ? name : "(null)");
    }

    /* The exact v9 regression: with a 4 byte table read at an 8 byte stride,
       ordinal 0 would have resolved to "_exit". */
    const char *first = GNImportSymbolName(header, gBlob, size, 0);
    char what[128];
    snprintf(what, sizeof(what), "%s ordinal 0 is not the next entry (stride)", label);
    check(!first || strcmp(first, "_exit") != 0, what, first ? first : "(null)");

    snprintf(what, sizeof(what), "%s ordinal == count is rejected", label);
    check(GNImportSymbolName(header, gBlob, size, NAME_COUNT) == NULL, what, NULL);

    snprintf(what, sizeof(what), "%s a huge ordinal is rejected", label);
    check(GNImportSymbolName(header, gBlob, size, 0xFFFFFFu) == NULL, what, NULL);
}

int main(void) {
    printf("rebind decoder test\n");

    test_format(GN_IMPORT, "format 1 (IMPORT)");
    test_format(GN_IMPORT_ADDEND, "format 2 (IMPORT_ADDEND)");
    test_format(GN_IMPORT_ADDEND64, "format 3 (IMPORT_ADDEND64)");

    /* --- the paths that used to hand strcmp a pointer into nowhere --------- */

    size_t size = 0;
    GNFixupsHeader *header = build_blob(GN_IMPORT, 3, &size);

    header->imports_format = 9;                     /* unknown */
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "an unknown import format is rejected", NULL);

    header->imports_format = GN_IMPORT;
    header->symbols_format = 1;                     /* compressed */
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "a compressed symbol table is rejected", NULL);

    header->symbols_format = GN_SYMBOLS_UNCOMPRESSED;
    header->imports_count = 4096;                   /* table no longer fits */
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "an import table past the end of the blob is rejected", NULL);

    header = build_blob(GN_IMPORT, 3, &size);
    header->symbols_offset = (uint32_t)size;        /* pool starts past the blob */
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "a symbol pool past the end of the blob is rejected", NULL);

    header = build_blob(GN_IMPORT, 3, &size);
    header->symbols_offset = (uint32_t)size - 3;
    memset(gBlob + size - 3, 'x', 3);               /* no terminator in range */
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "a name that is not terminated inside the blob is rejected", NULL);

    header = build_blob(GN_IMPORT, 3, &size);
    uint32_t raw = (0x7FFFFFu) << 9;                /* largest possible offset */
    memcpy(gBlob + header->imports_offset, &raw, sizeof(raw));
    check(GNImportSymbolName(header, gBlob, size, 0) == NULL,
          "an out-of-range name offset is rejected", NULL);

    header = build_blob(GN_IMPORT, 3, &size);
    check(GNImportSymbolName(header, gBlob, sizeof(GNFixupsHeader) - 1, 0) == NULL,
          "a truncated header is rejected", NULL);

    if (gFailures) {
        printf("\n%d check(s) failed\n", gFailures);
        return 1;
    }
    printf("\nall checks passed\n");
    return 0;
}
"""


def main():
    if not SOURCE.exists():
        raise SystemExit("missing %s" % SOURCE)

    harness = build_harness()

    with tempfile.TemporaryDirectory(prefix="gnrebindtest-") as workdir:
        directory = pathlib.Path(workdir)
        source = directory / "rebind_decoder_test.c"
        binary = directory / "rebind_decoder_test"
        source.write_text(harness, encoding="utf-8")

        compile_command = ["cc", "-std=c99", "-Wall", "-Wextra", "-Wno-unused-parameter",
                           "-O1", str(source), "-o", str(binary)]
        result = subprocess.run(compile_command, capture_output=True, text=True)
        if result.returncode != 0:
            print("error: the extracted decoder does not compile:", file=sys.stderr)
            print(result.stdout + result.stderr, file=sys.stderr)
            return 1
        if result.stderr.strip():
            # A warning here is about the extracted harness, not about the
            # decoder's behaviour - report it, but do not fail the build on a
            # diagnostic a different clang version may or may not emit.
            sys.stderr.write("note: compiler diagnostics for the harness:\n")
            sys.stderr.write(result.stderr)

        run = subprocess.run([str(binary)], capture_output=True, text=True)
        sys.stdout.write(run.stdout)
        if run.returncode != 0:
            sys.stderr.write(run.stderr)
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
